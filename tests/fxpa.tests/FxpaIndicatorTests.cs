using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;
using Xunit;

namespace fxpa.tests;

/// <summary>
/// Golden-master tests for FXPA's OWN indicator classes (the ones in
/// Analyzer/Indicator/Enahnced and Analyzer/Indicator/Custom), as opposed
/// to the raw TA-Lib catalog covered by CatalogGoldenTests.
///
/// These wrappers add their own buffering, period defaults and price
/// conventions on top of TA-Lib - for example FXPA's MACD runs on
/// BarData.Average = (O+H+L+C)/4 rather than on close - so they need
/// their own reference values. Those are generated by
/// tests/golden/generate_goldens.py from the canonical C TA-Lib, using
/// exactly the parameters and conventions the application uses.
///
/// The two genuinely custom indicators (PinBarCustom, ShadowTraceCustom)
/// have no external reference; their fixtures are captured from the
/// current implementation (see the class comments on those tests).
/// </summary>
public class FxpaIndicatorTests
{
    private static string GoldenDir => Path.Combine(System.AppContext.BaseDirectory, "golden");

    private sealed record Series(double[] Close, double[] High, double[] Low, double[] Volume);

    private static Series LoadSeries()
    {
        using var doc = JsonDocument.Parse(File.ReadAllText(Path.Combine(GoldenDir, "inputs.json")));
        var root = doc.RootElement;
        static double[] Read(JsonElement e) => e.EnumerateArray().Select(v => v.GetDouble()).ToArray();
        return new Series(
            Close: Read(root.GetProperty("close")),
            High: Read(root.GetProperty("high")),
            Low: Read(root.GetProperty("low")),
            Volume: Read(root.GetProperty("volume")));
    }

    private static FakeDataProvider Provider()
    {
        var s = LoadSeries();
        return new FakeDataProvider(s.Close, s.High, s.Low, s.Volume, new DateTime(2010, 12, 27, 14, 40, 0));
    }

    private static double[] Run(Indicator indicator, FakeDataProvider provider)
    {
        Assert.True(indicator.Initialize(provider), "indicator failed to initialize");
        indicator.Calculate();
        var set = indicator.Results.ResultSets[0];
        Assert.NotNull(set);
        return set.Values;
    }

    private static JsonDocument Golden(string function)
    {
        var path = Path.Combine(GoldenDir, "fxpa", function + ".json");
        Assert.True(File.Exists(path), $"missing golden fixture: {path}");
        return JsonDocument.Parse(File.ReadAllText(path));
    }

    /// <summary>
    /// Compares an indicator result set against its fixture. The wrapper
    /// reports a warm-up index; the golden holds only the settled values,
    /// so the tail of the produced series is compared.
    /// </summary>
    private static void VerifyTail(JsonDocument golden, string outputName, double[] actual)
    {
        var root = golden.RootElement;
        double tolerance = root.GetProperty("tolerance").GetDouble();
        double[] expected = root.GetProperty("outputs").GetProperty(outputName)
                                 .EnumerateArray().Select(v => v.GetDouble()).ToArray();

        Assert.True(actual.Length >= expected.Length,
            $"produced {actual.Length} values, expected at least {expected.Length}");

        int offset = actual.Length - expected.Length;
        for (int i = 0; i < expected.Length; i++)
        {
            double value = actual[offset + i];
            Assert.False(double.IsNaN(value), $"'{outputName}' is NaN at [{offset + i}]");
            Assert.True(Math.Abs(value - expected[i]) <= tolerance,
                $"'{outputName}' diverges at [{offset + i}]: expected {expected[i]}, actual {value} (tolerance {tolerance})");
        }
    }

    [Fact]
    public void Atr_indicator_matches_c_reference()
    {
        using var golden = Golden("ATR");
        var provider = Provider();
        var indicator = new ATR();
        double[] actual = Run(indicator, provider);

        VerifyTail(golden, "outReal", actual);
    }

