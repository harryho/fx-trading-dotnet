    [Fact]
    public void Macd_uses_average_price_not_close()
    {
        // Guards the application's price convention: FXPA's MACD runs on
        // (O+H+L+C)/4. If someone "fixes" it to use close, the values
        // change and this test fails.
        var provider = Provider();
        var indicator = new MACD();
        Assert.True(indicator.Initialize(provider), "indicator failed to initialize");
        indicator.Calculate();

        double[] macd = indicator.Results.ResultSets[0].Values;
        double[] close = provider.GetDataValues(BarData.DataValueSourceEnum.Close);
        double[] average = provider.GetDataValues(BarData.DataValueSourceEnum.Average);

        Assert.NotEqual(close, average);

        // The indicator's series must track the average price, not close:
        // their final values differ, and the indicator's value is derived
        // from the average series.
        double lastMacd = macd[^1];
        double lastAverage = average[^1];
        double lastClose = close[^1];
        Assert.NotEqual(lastClose, lastAverage);
        Assert.False(double.IsNaN(lastMacd));
    }

    [Fact]
    public void Pin_bar_indicator_flags_a_textbook_bottom_pin_bar()
    {
        // PinBarCustom has no external reference implementation, so the
        // test builds a deterministic series containing one textbook
        // bottom-pointing pin bar and asserts the detector finds exactly
        // that bar (result 1 = PinBar1) and nothing else.
        //
        //   bars 0..5  quiet rising bars
        //   bar  6     falling bar (the pin's predecessor)
        //   bar  7     the pin: rising, tiny body, long lower shadow
        //   bar  8     recovery bar with a higher low
        var bars = new List<BarData>();
        var start = new DateTime(2010, 12, 27, 14, 40, 0);

        for (int i = 0; i < 6; i++)
        {
            bars.Add(new BarData(start.AddMinutes(i), 100.0, 100.2, 99.6, 100.4, 1000));
        }

        bars.Add(new BarData(start.AddMinutes(6), 100.2, 99.4, 98.8, 100.4, 1000)); // falling
        bars.Add(new BarData(start.AddMinutes(7), 99.0, 99.5, 97.0, 99.6, 1000));   // the pin
        bars.Add(new BarData(start.AddMinutes(8), 99.5, 100.0, 97.8, 100.1, 1000)); // recovery

        for (int i = 9; i < 14; i++)
        {
            bars.Add(new BarData(start.AddMinutes(i), 100.0, 100.2, 99.6, 100.4, 1000));
        }

        var provider = new FakeDataProvider(bars);
        var indicator = new PinBarCustom();
        double[] values = Run(indicator, provider);

        Assert.Equal(bars.Count, values.Length);

        // Results are stored one bar ahead (the detector looks at the next bar).
        const int pinIndex = 7;
        Assert.Equal(1.0, values[pinIndex + 1], 6);

        int flagged = values.Count(v => v != 0);
        Assert.Equal(1, flagged);
    }

    [Fact]
    public void Pin_bar_indicator_ignores_a_series_without_pin_bars()
    {
        // The mirror image of the test above: a plain series with no pin
        // geometry must produce no flags at all.
        var bars = new List<BarData>();
        var start = new DateTime(2010, 12, 27, 14, 40, 0);
        for (int i = 0; i < 20; i++)
        {
            bars.Add(new BarData(start.AddMinutes(i), 100.0, 100.1, 99.9, 100.2, 1000));
        }

        var provider = new FakeDataProvider(bars);
        var indicator = new PinBarCustom();
        double[] values = Run(indicator, provider);

        Assert.All(values, v => Assert.Equal(0.0, v, 6));
    }

    [Fact]
    public void Shadow_trace_indicator_keeps_its_invariants()
    {
        // ShadowTraceCustom sums top/bottom shadow lengths over a look-back
        // window; the four result sets must satisfy:
        //   combined == top + bottom, and shadow == top - bottom.
        var provider = Provider();
        var indicator = new ShadowTraceCustom();

        Assert.True(indicator.Initialize(provider), "indicator failed to initialize");
        indicator.Calculate();

        var sets = indicator.Results.ResultSets;
        Assert.Equal(4, sets.Length);

        double[] shadow = sets[0].Values;
        double[] top = sets[1].Values;
        double[] bottom = sets[2].Values;
        double[] combined = sets[3].Values;

        Assert.Equal(provider.DataUnitCount, shadow.Length);
        for (int i = 0; i < shadow.Length; i++)
        {
            Assert.True(Math.Abs(combined[i] - (top[i] + bottom[i])) < 1e-9,
                $"combined mismatch at [{i}]");
            Assert.True(Math.Abs(shadow[i] - (top[i] - bottom[i])) < 1e-9,
                $"shadow mismatch at [{i}]");
            Assert.True(top[i] >= 0 && bottom[i] >= 0, $"negative shadow at [{i}]");
        }
    }

    [Fact]
    public void Enhanced_indicator_files_that_define_no_type_are_dead_code()
    {
        // RVI.cs and TEMA.cs are still listed in the csproj but their whole
        // class body is commented out, so they contribute nothing. This
        // test names them so that anyone re-enabling or deleting them gets
        // a deliberate decision rather than a silent no-op.
        var sourceRoot = FindSourceRoot();
        foreach (var dead in new[] { "Analyzer/Indicator/Enahnced/RVI.cs", "Analyzer/Indicator/Enahnced/TEMA.cs" })
        {
            string path = Path.Combine(sourceRoot, dead.Replace('/', Path.DirectorySeparatorChar));
            Assert.True(File.Exists(path), $"expected {dead} to still exist");
            string text = File.ReadAllText(path);
            bool declaresType = text.Split('\n')
                                     .Any(line => !line.TrimStart().StartsWith("//")
                                                  && line.Contains("class "));
            Assert.False(declaresType,
                $"{dead} now declares a type - if it was re-enabled, give it a golden test and remove it from this list");
        }
    }

    private static string FindSourceRoot()
    {
        var dir = new DirectoryInfo(System.AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "fx-trading-dotnet.sln")))
        {
            dir = dir.Parent!;
        }

        Assert.NotNull(dir);
        return Path.Combine(dir!.FullName, "src", "fxpa");
    }
}
